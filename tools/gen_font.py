#!/usr/bin/env python3
"""Generate ui/font_data.c from the public-domain X11 "misc-fixed" bitmap fonts.

The generated file is committed, so this only needs to be re-run to change the
fonts. Requires Pillow and the fonts (Debian/Ubuntu: apt install xfonts-base).
"""
import gzip
import io
import sys
from PIL import PcfFontFile

FONT_DIR = "/usr/share/fonts/X11/misc"
# (C identifier, file, cell width, cell height)
FONTS = [
    ("small", "4x6.pcf.gz", 4, 6),
    ("normal", "5x8.pcf.gz", 5, 8),
    ("bold", "6x13B.pcf.gz", 6, 13),
    ("big", "9x15B.pcf.gz", 9, 15),
]
FIRST, LAST = 0x20, 0x7E


def load(path):
    with gzip.open(path, "rb") as f:
        return PcfFontFile.PcfFontFile(io.BytesIO(f.read()))


def glyph_rows(font, code, width, height):
    """Rows of the character cell as integers, MSB = leftmost pixel."""
    g = font.glyph[code] if code < len(font.glyph) else None
    rows = [0] * height
    if g is None:
        return rows
    (_adv, _), (dx0, dy0, dx1, dy1), _src, image = g
    ascent = font.info_ascent if hasattr(font, "info_ascent") else None
    for y in range(image.size[1]):
        cy = y + dy0 + ASCENT[0]
        if not 0 <= cy < height:
            continue
        for x in range(image.size[0]):
            cx = x + dx0
            if 0 <= cx < width and image.getpixel((x, y)):
                rows[cy] |= 1 << (15 - cx)
    return rows


ASCENT = [0]


def main(out_path):
    out = ["/* Generated by tools/gen_font.py from X11 misc-fixed (public domain). */",
           '#include "font.h"', ""]
    for ident, fname, w, h in FONTS:
        font = load(f"{FONT_DIR}/{fname}")
        # ascent: distance from the cell top to the baseline
        tops = [font.glyph[c][1][1] for c in range(FIRST, LAST + 1) if font.glyph[c]]
        ASCENT[0] = -min(tops)
        wide = w > 8
        ctype = "uint16_t" if wide else "uint8_t"
        out.append(f"static const {ctype} {ident}_rows[] = {{")
        for code in range(FIRST, LAST + 1):
            rows = glyph_rows(font, code, w, h)
            vals = [(r if wide else r >> 8) for r in rows]
            fmt = "0x%04X" if wide else "0x%02X"
            ch = chr(code) if code not in (0x5C,) else "backslash"
            out.append("    " + ", ".join(fmt % v for v in vals) + f", /* {ch} */")
        out.append("};")
        out.append(f"const FontDef font_{ident} = {{{w}, {h}, {FIRST}, {LAST - FIRST + 1}, "
                   f"{'true' if wide else 'false'}, {ident}_rows}};")
        out.append("")
    with open(out_path, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "ui/font_data.c")
